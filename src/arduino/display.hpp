// index of a character inside display_operator, default to _ (7)
// order must match display_operator below
inline static char display_operator_chars(char c) {
    switch (c) {
    case '+': return 0;
    case '-': return 1;
    case '*': return 2;
    case '/': return 3;
    case '^': return 4;
    case 'R': return 5;
    case '=': return 6;
    case '_': return 7;
    case '.': return 8;
    case '(': return 9;
    case ')': return 10;
    default:  return 7;
    }
}
